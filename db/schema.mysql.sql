CREATE TABLE IF NOT EXISTS findings (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  title VARCHAR(200) NOT NULL, severity ENUM('alto','medio','bajo') NOT NULL DEFAULT 'medio',
  recommendation TEXT NULL, body TEXT NULL, created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS checklist_items (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  label VARCHAR(200) NOT NULL, category VARCHAR(80) NULL, done TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS requests (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  item VARCHAR(255) NOT NULL, status ENUM('pedido','recibido','pendiente') NOT NULL DEFAULT 'pedido',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS time_entries (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL, user_id INT NULL,
  work_date DATE NULL, minutes INT NOT NULL DEFAULT 0, rate DECIMAL(10,2) NOT NULL DEFAULT 0,
  billable TINYINT NOT NULL DEFAULT 1, invoiced TINYINT NOT NULL DEFAULT 0, note VARCHAR(255) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS conflicts (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(200) NOT NULL, note TEXT NULL,
  created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
  id INT AUTO_INCREMENT PRIMARY KEY, ip VARCHAR(64), email VARCHAR(254),
  at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX (email, at), INDEX (ip, at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
