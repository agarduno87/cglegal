CREATE TABLE IF NOT EXISTS deadlines (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  title VARCHAR(200) NOT NULL, due_date DATE NOT NULL,
  kind ENUM('procesal','contractual','fiscal','administrativo','otro') NOT NULL DEFAULT 'otro',
  done TINYINT NOT NULL DEFAULT 0, created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tasks (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  title VARCHAR(200) NOT NULL, assignee_id INT NULL, due_date DATE NULL,
  status ENUM('pendiente','en_proceso','hecha') NOT NULL DEFAULT 'pendiente',
  created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (assignee_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS parties (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  name VARCHAR(160) NOT NULL,
  role ENUM('cliente','contraparte','tercero','representante','notario','autoridad','co-counsel','perito') NOT NULL DEFAULT 'tercero',
  org VARCHAR(160) NULL, email VARCHAR(254) NULL, phone VARCHAR(40) NULL, notes TEXT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS documents (
  id INT AUTO_INCREMENT PRIMARY KEY, case_id INT NOT NULL,
  orig_name VARCHAR(200) NOT NULL, stored_name VARCHAR(120) NOT NULL,
  category VARCHAR(40) DEFAULT 'otro', mime VARCHAR(120), size INT,
  confidential TINYINT NOT NULL DEFAULT 1,
  visible_to_client TINYINT NOT NULL DEFAULT 0,
  uploaded_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
